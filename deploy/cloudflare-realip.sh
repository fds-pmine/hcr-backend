#!/bin/sh
# Generate nginx real-IP configuration for Cloudflare's ranges.
#
# Install the output with the sequence in docs/DEPLOY.md §2.1, which checks it
# with `nginx -t` before it replaces the live file.
#
# Behind Cloudflare, `$remote_addr` is a Cloudflare edge address, not the
# visitor's. Two things break as a result:
#
#   * `limit_req` keys every request to a handful of addresses, so the rate
#     limit throttles all of your users collectively instead of individually.
#   * Access logs record Cloudflare, which makes them useless for working out
#     what happened.
#
# `real_ip_header CF-Connecting-IP` fixes both — but only in combination with
# `set_real_ip_from`, which is what stops anyone else claiming to be a visitor
# by sending that header themselves. Trusting the header without the ranges is
# worse than not doing this at all.
#
# Cloudflare adds ranges occasionally; re-run after a change and reload.
set -euf

printf '# Generated by deploy/cloudflare-realip.sh — do not edit by hand.\n'
printf '# Source: https://www.cloudflare.com/ips-v4 and /ips-v6\n\n'

for url in https://www.cloudflare.com/ips-v4 https://www.cloudflare.com/ips-v6; do
    # Into a variable, so a failed fetch stops the script (set -e) and a list
    # without a trailing newline still yields its last range.
    ranges=$(curl -fsS "$url")
    found=0
    # Unquoted on purpose: split on whitespace; set -f stops globbing.
    for range in $ranges; do
        # A CIDR range and nothing else: never /0, and no character that could
        # end the nginx directive or start another.
        case $range in
        */0* | *[!0123456789abcdefABCDEF.:/]*) ;;
        */*) printf 'set_real_ip_from %s;\n' "$range"; found=1; continue ;;
        esac
        echo "cloudflare-realip.sh: refusing '$range' from $url" >&2
        exit 1
    done
    if [ "$found" = 0 ]; then
        echo "cloudflare-realip.sh: $url returned no ranges" >&2
        exit 1
    fi
done

printf '\nreal_ip_header CF-Connecting-IP;\n'
